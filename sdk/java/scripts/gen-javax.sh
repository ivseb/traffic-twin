#!/bin/sh
# Regenerates the javax.servlet (Servlet 3.1/4.0, Jetty 9-10, Tomcat 8.5-9) variant of the servlet
# integration from the jakarta one, so the two never drift. Run from sdk/java after editing
# sdk/src/main/java/io/github/ivseb/traffictwin/servlet/. CI runs it and fails on any diff.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
src="$here/sdk/src/main/java/io/github/ivseb/traffictwin/servlet"
dst="$here/sdk-servlet-javax/src/main/java/io/github/ivseb/traffictwin/servlet/javax"
mkdir -p "$dst"
for f in TrafficTwinFilter TrafficTwinInitializer; do
  sed -e 's/jakarta\.servlet/javax.servlet/g' \
      -e 's/^package io\.github\.ivseb\.traffictwin\.servlet;/package io.github.ivseb.traffictwin.servlet.javax;/' \
      -e '1i\
// GENERATED by scripts/gen-javax.sh from the jakarta variant. Do not edit.' \
      "$src/$f.java" > "$dst/$f.java"
done
mkdir -p "$here/sdk-servlet-javax/src/main/resources/META-INF/services"
printf 'io.github.ivseb.traffictwin.servlet.javax.TrafficTwinInitializer\n' \
  > "$here/sdk-servlet-javax/src/main/resources/META-INF/services/javax.servlet.ServletContainerInitializer"
