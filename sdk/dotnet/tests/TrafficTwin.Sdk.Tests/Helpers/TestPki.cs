using System;
using System.Collections.ObjectModel;
using System.Net;
using System.Net.Security;
using System.Reflection;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using TrafficTwin.Sdk.Fleet;

namespace TrafficTwin.Sdk.Tests.Helpers;

/// <summary>A throw-away PKI for the fake tt-core: root CA, server certificate for 127.0.0.1, client certificates from CSRs.</summary>
internal sealed class TestPki : IDisposable
{
    private readonly ECDsa rootKey = ECDsa.Create(ECCurve.NamedCurves.nistP256);
    public X509Certificate2 Root { get; }
    public X509Certificate2 Server { get; }
    private long serial = 1000;

    public TestPki(string rootName = "traffic-twin test root")
    {
        var req = new CertificateRequest("CN=" + rootName, rootKey, HashAlgorithmName.SHA256);
        req.CertificateExtensions.Add(new X509BasicConstraintsExtension(true, false, 0, true));
        req.CertificateExtensions.Add(new X509KeyUsageExtension(X509KeyUsageFlags.KeyCertSign | X509KeyUsageFlags.CrlSign, true));
        req.CertificateExtensions.Add(new X509SubjectKeyIdentifierExtension(req.PublicKey, false));
        Root = req.CreateSelfSigned(DateTimeOffset.UtcNow.AddDays(-1), DateTimeOffset.UtcNow.AddDays(30));

        using var skey = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        var sreq = new CertificateRequest("CN=tt-core.test", skey, HashAlgorithmName.SHA256);
        var san = new SubjectAlternativeNameBuilder();
        san.AddDnsName("localhost");
        san.AddIpAddress(IPAddress.Loopback);
        sreq.CertificateExtensions.Add(san.Build());
        sreq.CertificateExtensions.Add(new X509BasicConstraintsExtension(false, false, 0, true));
        sreq.CertificateExtensions.Add(new X509KeyUsageExtension(X509KeyUsageFlags.DigitalSignature, true));
        sreq.CertificateExtensions.Add(new X509EnhancedKeyUsageExtension(new OidCollection { new Oid("1.3.6.1.5.5.7.3.1") }, false));
        using var issued = sreq.Create(Root, DateTimeOffset.UtcNow.AddDays(-1), DateTimeOffset.UtcNow.AddDays(10), SerialNumber());
        using var withKey = issued.CopyWithPrivateKey(skey);
        Server = new X509Certificate2(withKey.Export(X509ContentType.Pfx));
    }

    private byte[] SerialNumber() => BitConverter.GetBytes(System.Threading.Interlocked.Increment(ref serial));

    public string RootPem => Root.ExportCertificatePem();

    public byte[] RootDer => Root.RawData;

    public string Pin => FleetTls.PinOf(RootDer);

    /// <summary>Signs the PKCS#10 request of a source (the private key stays with the source).</summary>
    public string IssueFromCsr(string csrPem, string sourceId, DateTimeOffset? notAfter = null)
    {
        var req = CertificateRequest.LoadSigningRequestPem(csrPem, HashAlgorithmName.SHA256, CertificateRequestLoadOptions.SkipSignatureValidation | CertificateRequestLoadOptions.UnsafeLoadCertificateExtensions);
        var san = new SubjectAlternativeNameBuilder();
        san.AddDnsName(sourceId);
        req.CertificateExtensions.Add(san.Build());
        req.CertificateExtensions.Add(new X509EnhancedKeyUsageExtension(new OidCollection { new Oid("1.3.6.1.5.5.7.3.2") }, false));
        using var cert = req.Create(Root, DateTimeOffset.UtcNow.AddDays(-1), notAfter ?? DateTimeOffset.UtcNow.AddDays(7), SerialNumber());
        return cert.ExportCertificatePem();
    }

    /// <summary>A certificate and key generated by the "server" (the enrollment without CSR).</summary>
    public (string CertPem, string KeyPem) IssueWithKey(string sourceId)
    {
        using var key = ECDsa.Create(ECCurve.NamedCurves.nistP256);
        var req = new CertificateRequest("CN=" + sourceId, key, HashAlgorithmName.SHA256);
        return (IssueFromCsr(req.CreateSigningRequestPem(), sourceId), key.ExportPkcs8PrivateKeyPem());
    }

    /// <summary>
    /// .NET's SslStream never sends the root of a chain (it strips self-signed roots), but tt-core (Go) presents it and
    /// the enrollment pin is the hash of that root. For the fake core the root is added to the context by reflection.
    /// </summary>
    public SslStreamCertificateContext ServerContext(bool includeRoot = true)
    {
        var ctx = SslStreamCertificateContext.Create(Server, null, offline: true);
        if (!includeRoot) return ctx;
        var rootCopy = new X509Certificate2(Root.RawData);
        BindingFlags bf = BindingFlags.NonPublic | BindingFlags.Instance;
        Type t = typeof(SslStreamCertificateContext);
        FieldInfo? f1 = t.GetField("<IntermediateCertificates>k__BackingField", bf);
        FieldInfo? f2 = t.GetField("_privateIntermediateCertificates", bf);
        if (f1 == null || f2 == null) throw new NotSupportedException("this runtime's SslStreamCertificateContext layout is unknown; cannot present the root in the chain");
        f1.SetValue(ctx, new ReadOnlyCollection<X509Certificate2>(new[] { rootCopy }));
        f2.SetValue(ctx, new[] { rootCopy });
        return ctx;
    }

    public void Dispose()
    {
        rootKey.Dispose();
        Root.Dispose();
        Server.Dispose();
    }
}
