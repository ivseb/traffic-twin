// omap is a map that keeps insertion order when rendered as YAML. Prism
// answers with the first example when no Prefer header is sent, so the order
// of examples is part of the behaviour.
type omap struct {
	keys []string
	vals map[string]any
}

func newOmap() *omap { return &omap{vals: map[string]any{}} }

func (o *omap) set(k string, v any) {
	if _, ok := o.vals[k]; !ok {
		o.keys = append(o.keys, k)
	}
	o.vals[k] = v
}

// MarshalYAML implements yaml.Marshaler.
func (o *omap) MarshalYAML() (any, error) {
	n := &yaml.Node{Kind: yaml.MappingNode}
	for _, k := range o.keys {
		kn := &yaml.Node{}
		if err := kn.Encode(k); err != nil {
			return nil, err
		}
		vn := &yaml.Node{}
		if err := vn.Encode(normalize(o.vals[k])); err != nil {
			return nil, err
		}
		n.Content = append(n.Content, kn, vn)
	}
	return n, nil
}

func exportPrism(m *model, _ PrismOptions) ([]outFile, *Report) {
	rep := newReport("prism", m.in.Manifest.PackID)
	rep.addNotes(m.notes)
	var files []outFile

	for _, svc := range m.in.Services {
		ops := m.opsBySvc[svc.Name]
		if ops == nil {
			continue
		}
		name := svc.Name
		rep.count("services", 1)
		doc := stripExt(deepCopy(svc.Contract)).(map[string]any)
		info := asMap(doc["info"])
		if info == nil {
			info = map[string]any{}
			doc["info"] = info
		}
		info["title"] = name
		info["version"] = apiVersion(svc, m.in.Manifest.CreatedAt)
		paths := asMap(doc["paths"])

		// Extra examples from the world, grouped per operation/status/media.
		type slot struct {
			status int
			media  string
		}
		extra := map[string]map[slot][]example{}
		for _, l := range m.lookups[name] {
			if extra[l.Op.Key] == nil {
				extra[l.Op.Key] = map[slot][]example{}
			}
			for _, v := range l.Views {
				s := slot{v.Status, v.Media}
				extra[l.Op.Key][s] = append(extra[l.Op.Key][s], example{v.Name, v.Body})
				rep.exported("example", "entity:"+l.Entity, 1)
			}
			if l.Foreign != nil {
				fv := l.Foreign
				s := slot{fv.Status, fv.Media}
				extra[l.Op.Key][s] = append(extra[l.Op.Key][s], example{fv.Name, fv.Body})
				rep.exported("example", "entity:"+l.Entity, 1)
				rep.lose("scope", "op:"+l.Service+" "+l.Op.Key, "owner-scoped read: the answer for another customer is an example (Prefer: code="+fmt.Sprint(fv.Status)+", example="+fv.Name+"), never chosen by a session customer", 1)
			}
		}

		for _, op := range ops {
			rep.count("operations", 1)
			item := asMap(paths[op.Path])
			o := asMap(item[strings.ToLower(op.Method)])
			resps := asMap(o["responses"])
			if resps == nil {
				resps = map[string]any{}
				o["responses"] = resps
			}
			slots := extra[op.Key]
			var keys []slot
			for s := range slots {
				keys = append(keys, s)
			}
			sort.Slice(keys, func(i, j int) bool {
				if keys[i].status != keys[j].status {
					return keys[i].status < keys[j].status
				}
				return keys[i].media < keys[j].media
			})
			for _, s := range keys {
				code := strconv.Itoa(s.status)
				r := asMap(resps[code])
				if r == nil {
					r = map[string]any{"description": "Generated by traffic-twin from the synthetic world"}
					resps[code] = r
				}
				content := asMap(r["content"])
				if content == nil {
					content = map[string]any{}
					r["content"] = content
				}
				mm := asMap(content[s.media])
				if mm == nil {
					mm = map[string]any{}
					content[s.media] = mm
				}
				ex := newOmap()
				// Contract examples first (sorted), world examples after.
				old := asMap(mm["examples"])
				for _, n := range sortedKeys(old) {
					ex.set(n, old[n])
				}
				if v, ok := mm["example"]; ok {
					ex.set("default", map[string]any{"value": v})
					delete(mm, "example")
				}
				for _, e := range slots[s] {
					ex.set(e.Name, map[string]any{"value": e.Value})
				}
				mm["examples"] = ex
			}
			for _, r := range op.Responses {
				for range r.Examples {
					rep.exported("example", "op:"+name+" "+op.Key, 1)
				}
			}
			el := "op:" + name + " " + op.Key
			if f, ok := m.faults[name+"|"+op.Key]; ok {
				for _, fs := range f.Statuses {
					code := fmt.Sprintf("code=%d", fs.Status)
					if fs.Example != "" {
						code += ", example=" + fs.Example
					}
					rep.lose("probabilistic-fault", el, fmt.Sprintf("status %d observed with p=%v: Prism never injects errors at random; ask for it with Prefer: %s", fs.Status, fs.P, code), 1)
				}
				for _, ne := range f.NetErrors {
					rep.lose("probabilistic-fault", el, fmt.Sprintf("network error %q (p=%v) cannot be expressed in Prism", ne.Kind, ne.P), 1)
				}
			}
			if l := m.latencyOf(op); l != nil {
				rep.lose("latency-distribution", el, "Prism has no response delay: observed latency is dropped", 1)
			}
		}
		for _, id := range sortedKeys(ruleIDs(m.lookups[name])) {
			rep.lose("state", "rule:"+id, "Prism is stateless: every step of the scenario is a separate named example, selected with Prefer: example=<name>; no step ever follows another", 1)
			rep.lose("time", "rule:"+id, "no clock and no figurative delays (after: "+m.delayInfo(id)+")", 1)
		}
		files = append(files, outFile{Path: "prism/" + name + "/" + name + ".openapi.yaml", Data: marshalYAML(doc)})
	}
	rep.count("files", len(files))
	rep.count("rules_approved", m.stats.ApprovedRules)
	m.reportCommon(rep)
	rep.setPresets(m.presetReports(TargetPrism, presetOpts{}))
	return files, rep.build(files)
}

func ruleIDs(ls []*lookup) map[string]bool {
	out := map[string]bool{}
	for _, l := range ls {
		if l.RuleID != "" && l.stateful() {
			out[l.RuleID] = true
		}
	}
	return out
}
