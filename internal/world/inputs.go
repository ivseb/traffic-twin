// The inputs of the generator are small interfaces so that the producers
// (internal/contract, internal/miner, internal/intake) can be plugged in as
// they land, and tests can use fakes.

// Contract is one inferred contract as the contract inference hands it over.
type Contract struct {
	// Service is the service name (as in events and rules).
	Service string
	// Group is the group whose traffic the contract was inferred from (""
	// for every group's).
	Group string
	// Doc is the OpenAPI 3.1 document (JSON) with x-tt-* extensions.
	Doc []byte
	// External marks a service called by the system under test (outbound),
	// not by customers: the world never simulates its operations
	// (docs/spec/rules.md 6.1).
	External bool
	// Alias is the name the external service takes in packs when host
	// anonymization is on (upstream_alias); optional.
	Alias string
	// Declared lists the observed keep values that appear in Doc (enum
	// values, error codes and messages in examples) with the number of
	// distinct subjects that produced each one. Values below k_min are
	// removed by the pack writer and refused by the gate.
	Declared map[string]int64
	// Synthetic lists the values of Doc generated by the inference
	// (examples, ids): the gate accepts them as synthetic.
	Synthetic []string
	// Combos lists the published field combinations of Doc
	// (x-tt-dependencies) with their distinct subjects, keyed by
	// contract.ComboKey; the gate checks every combination against it.
	Combos map[string]int64
}

// ContractsSource returns the current contracts.
type ContractsSource interface {
	Contracts(ctx context.Context) ([]Contract, error)
}

// GroupContractsSource is implemented by contract sources that infer the
// contracts of one group's traffic (tt-core): two groups calling the same
// host pattern have two contracts, and a world of one group gets its own.
type GroupContractsSource interface {
	ContractsIn(ctx context.Context, group string) ([]Contract, error)
}

// RuleSet is the set of approved rules as the rule store hands it over.
type RuleSet struct {
	// Doc is a tt.rules/v1 document. Rules that are not approved are
	// ignored.
	Doc []byte
	// OutcomeSubjects optionally gives, per rule id and outcome name, the
	// number of distinct subjects that experienced it (k check of
	// published outcomes). Without it the gate uses evidence.counts.outcomes.
	OutcomeSubjects map[string]map[string]int64
}

// RulesSource returns the approved rules.
type RulesSource interface {
	ApprovedRules(ctx context.Context) (*RuleSet, error)
}

// EventSource is the read side of the event store (*intake.Store).
type EventSource interface {
	Scan(ctx context.Context, q intake.Query, fn func(*intake.StoredEvent) error) error
}

// OutcomeSource optionally tells which rule outcomes each subject
// experienced (the miner implements it). Keys are subject tokens, values
// map "rule-id/outcome" to a count. The map never leaves this package.
type OutcomeSource interface {
	SubjectOutcomes(ctx context.Context, from, to time.Time) (map[string]map[string]int64, error)
}

// Rules is a parsed rule set restricted to approved rules.
type Rules struct {
	Entities []pack.Entity
	Causal   []pack.CausalRule
	Batch    []pack.BatchRule
	// IDs lists the approved rule ids in file order.
	IDs []string
	// Doc is the approved rules document (generic, numbers as json.Number),
	// still with review and evidence blocks.
	Doc map[string]any
	// Skipped lists the approved rules left out because they cannot be used.
	Skipped []SkippedRule
	// Attributes are the customer attributes of the document (rules v1.9):
	// the generator gives every customer a value of each.
	Attributes []pack.Attribute

	ents map[string]*pack.Entity
}

// SkippedRule is an approved rule the generator could not use, and why.
type SkippedRule struct {
	ID     string `json:"id"`
	Reason string `json:"reason"`
	// Service is the service of the rule's cause ("" when unknown): a
	// world of one group tells only that group's skipped rules.
	Service string `json:"-"`
}

// Entity returns the entity named n.
func (r *Rules) Entity(n string) *pack.Entity { return r.ents[n] }

func decodeUseNumber(b []byte, v any) error {
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.UseNumber()
	if err := dec.Decode(v); err != nil {
		return err
	}
	if _, err := dec.Token(); err != io.EOF {
		return errors.New("trailing data")
	}
	return nil
}

// ParseRules parses a tt.rules/v1 document and keeps the approved rules,
// optionally only those listed in only. It checks the cross references the
// generator relies on. Without only, an approved rule that cannot be used
// (an entity no longer in the document, a bad schedule) is left out and
// listed in Skipped with the reason, so one broken rule of a team never
// stops the worlds of everybody; a rule asked for by id must be usable.
func ParseRules(doc []byte, only []string) (*Rules, error) {
	var top map[string]any
	if err := decodeUseNumber(doc, &top); err != nil {
		return nil, fmt.Errorf("rules: %w", err)
	}
	if top["format"] != "tt.rules/v1" {
		return nil, errors.New("rules: format must be tt.rules/v1")
	}
	want := map[string]bool{}
	for _, id := range only {
		want[id] = true
	}
	out := &Rules{ents: map[string]*pack.Entity{}}
	ents, _ := json.Marshal(top["entities"])
	if err := decodeUseNumber(ents, &out.Entities); err != nil {
		return nil, fmt.Errorf("rules: entities: %w", err)
	}
	for i := range out.Entities {
		e := &out.Entities[i]
		if e.Name == "" || e.IDPrefix == "" || e.IDField == "" {
			return nil, fmt.Errorf("rules: entity %q is incomplete", e.Name)
		}
		out.ents[e.Name] = e
	}
	if a, ok := top["attributes"]; ok {
		b, _ := json.Marshal(a)
		if err := decodeUseNumber(b, &out.Attributes); err != nil {
			return nil, fmt.Errorf("rules: attributes: %w", err)
		}
	}
	raw, _ := top["rules"].([]any)
	var kept []any
	for _, x := range raw {
		m, ok := x.(map[string]any)
		if !ok {
			return nil, errors.New("rules: a rule is not an object")
		}
		id, _ := m["id"].(string)
		if m["status"] != "approved" || (len(want) > 0 && !want[id]) {
			continue
		}
		var causal *pack.CausalRule
		var batch *pack.BatchRule
		err := func() error {
			b, _ := json.Marshal(m)
			switch m["kind"] {
			case "causal":
				var c pack.CausalRule
				if err := decodeUseNumber(b, &c); err != nil {
					return err
				}
				if err := checkCausal(&c, out.ents); err != nil {
					return err
				}
				causal = &c
			case "batch":
				var bt pack.BatchRule
				if err := decodeUseNumber(b, &bt); err != nil {
					return err
				}
				if out.ents[bt.Entity] == nil {
					return errors.New("unknown entity")
				}
				if _, err := parseCron(bt.Schedule); err != nil {
					return err
				}
				batch = &bt
			default:
				return errors.New("unknown kind")
			}
			return nil
		}()
		if err != nil {
			if len(want) > 0 {
				return nil, fmt.Errorf("rules: %s: %w", id, err)
			}
			sk := SkippedRule{ID: id, Reason: err.Error()}
			if c, ok := m["cause"].(map[string]any); ok {
				sk.Service, _ = c["service"].(string)
			}
			out.Skipped = append(out.Skipped, sk)
			continue
		}
		if causal != nil {
			out.Causal = append(out.Causal, *causal)
		} else {
			out.Batch = append(out.Batch, *batch)
		}
		out.IDs = append(out.IDs, id)
		kept = append(kept, m)
	}
	for id := range want {
		found := false
		for _, k := range out.IDs {
			found = found || k == id
		}
		if !found {
			return nil, fmt.Errorf("rules: %s is not an approved rule", id)
		}
	}
	sort.Strings(out.IDs)
	sort.SliceStable(out.Causal, func(i, j int) bool { return out.Causal[i].ID < out.Causal[j].ID })
	sort.SliceStable(out.Batch, func(i, j int) bool { return out.Batch[i].ID < out.Batch[j].ID })
	if kept == nil {
		kept = []any{}
	}
	top["rules"] = kept
	out.Doc = top
	return out, nil
}

func checkCausal(c *pack.CausalRule, ents map[string]*pack.Entity) error {
	ids := map[string]int{}
	for i, e := range c.Effects {
		if _, dup := ids[e.ID]; dup {
			return fmt.Errorf("duplicate effect %s", e.ID)
		}
		ids[e.ID] = i
		if e.Respond != nil {
			// A response effect changes answers of the mock, not the
			// world: the generator does not simulate it.
			continue
		}
		if e.TargetKey != nil {
			// rules v1.8: keyed records are not in the world (rules.md
			// 2.9); an effect on one applies in the mock only.
			continue
		}
		if ents[e.Entity] == nil {
			return fmt.Errorf("effect %s: unknown entity", e.ID)
		}
		if e.TargetAll {
			continue // rules v1.9: every entity of the customer
		}
		n := 0
		if e.Create != nil {
			n++
		}
		if e.Target != "" {
			n++
		}
		if e.TargetID != "" {
			n++
		}
		if n != 1 {
			return fmt.Errorf("effect %s: needs exactly one of create, target, target_id", e.ID)
		}
		if e.TargetID != "" {
			if _, ok := refVar(e.TargetID); !ok {
				return fmt.Errorf("effect %s: target_id must be ${var}", e.ID)
			}
		}
	}
	for _, e := range c.Effects {
		for _, d := range []string{e.Target, e.AfterEffect} {
			if _, ok := ids[d]; d != "" && !ok {
				return fmt.Errorf("effect %s: unknown effect %s", e.ID, d)
			}
		}
	}
	// after_effect must not loop.
	for _, e := range c.Effects {
		seen := map[string]bool{}
		for cur := e.ID; cur != ""; cur = c.Effects[ids[cur]].AfterEffect {
			if seen[cur] {
				return errors.New("after_effect cycle")
			}
			seen[cur] = true
		}
	}
	var sum float64
	for _, o := range c.Outcomes {
		sum += o.P
		for _, id := range o.Effects {
			if _, ok := ids[id]; !ok {
				return fmt.Errorf("outcome %s: unknown effect %s", o.Name, id)
			}
		}
	}
	if len(c.Outcomes) == 0 || sum < 0.999 || sum > 1.001 {
		return errors.New("outcome probabilities must sum to 1")
	}
	return nil
}
