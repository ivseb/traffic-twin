// Postman Collection v2.1 generated from the inferred OpenAPI document.
//
// The collection has one request per operation, grouped in a folder per
// first path segment. Request bodies carry the synthetic examples of the
// contract ("typical" first), the base URL is the collection variable
// {{baseUrl}} (Insomnia and Postman both resolve it from the environment) and
// each recorded response example becomes a saved response of the request.
// Insomnia and Postman also import the OpenAPI document itself.

// PostmanSchemaURL identifies the collection format.
const PostmanSchemaURL = "https://schema.getpostman.com/json/collection/v2.1.0/collection.json"

// PostmanBaseURLVar is the collection variable that holds the base URL.
const PostmanBaseURLVar = "baseUrl"

// DefaultPostmanBaseURL is the default value of {{baseUrl}}: the address of a mock
// started locally (`tt mock`, default --addr 127.0.0.1:8480). The Mock page of the
// console offers the collection with base_url set to the running mock's URL of the
// service (<mock>/__svc/<service>).
const DefaultPostmanBaseURL = "http://localhost:8480"

// DefaultPostmanServiceURL is the default {{baseUrl}} of a service's collection: the
// service on a locally started mock.
func DefaultPostmanServiceURL(service string) string {
	return DefaultPostmanBaseURL + "/__svc/" + url.PathEscape(service)
}

// PostmanOptions tune the collection.
type PostmanOptions struct {
	// Name of the collection (default: the service name).
	Name string
	// BaseURL is the default value of the baseUrl variable (default DefaultPostmanBaseURL).
	BaseURL string
}

type pmItem map[string]any

// PostmanCollection converts an OpenAPI 3.x document (JSON, as rendered by
// Contract.JSON) into a Postman Collection v2.1 (indented JSON).
func PostmanCollection(openapi []byte, o PostmanOptions) ([]byte, error) {
	var doc struct {
		Info struct {
			Title       string `json:"title"`
			Description string `json:"description"`
			Version     string `json:"version"`
		} `json:"info"`
		Paths map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(openapi, &doc); err != nil {
		return nil, fmt.Errorf("contract: postman: %w", err)
	}
	if len(doc.Paths) == 0 {
		return nil, errors.New("contract: postman: the document has no paths")
	}
	name := o.Name
	if name == "" {
		name = doc.Info.Title
	}
	if name == "" {
		name = "contract"
	}
	base := o.BaseURL
	if base == "" {
		base = DefaultPostmanBaseURL
	}

	paths := make([]string, 0, len(doc.Paths))
	for p := range doc.Paths {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var folders []string
	byFolder := map[string][]pmItem{}
	for _, path := range paths {
		methods := make([]string, 0, len(doc.Paths[path]))
		for m := range doc.Paths[path] {
			if isHTTPMethod(m) {
				methods = append(methods, m)
			}
		}
		sort.Slice(methods, func(i, j int) bool { return methodRank(methods[i]) < methodRank(methods[j]) })
		for _, m := range methods {
			var op openAPIOp
			if err := json.Unmarshal(doc.Paths[path][m], &op); err != nil {
				return nil, fmt.Errorf("contract: postman: %s %s: %w", m, path, err)
			}
			endpoint, _, _ := strings.Cut(path, "#") // a GraphQL operation goes with its endpoint
			folder := firstSegment(endpoint)
			if _, ok := byFolder[folder]; !ok {
				folders = append(folders, folder)
			}
			byFolder[folder] = append(byFolder[folder], postmanRequest(strings.ToUpper(m), path, &op))
		}
	}

	items := make([]any, 0, len(folders))
	for _, f := range folders {
		items = append(items, map[string]any{"name": "/" + f, "item": byFolder[f]})
	}
	desc := strings.TrimSpace(doc.Info.Description)
	if desc != "" {
		desc += "\n\n"
	}
	desc += "Generated by traffic-twin from the inferred OpenAPI contract. Set the `" + PostmanBaseURLVar + "` variable to the address of your mock. Postman and Insomnia can also import the OpenAPI document directly."
	coll := map[string]any{
		"info": map[string]any{
			"name":        name,
			"description": desc,
			"schema":      PostmanSchemaURL,
		},
		"item": items,
		"variable": []any{map[string]any{
			"key": PostmanBaseURLVar, "value": base, "type": "string",
			"description": "Address of the mock that answers instead of the real service.",
		}},
	}
	return json.MarshalIndent(coll, "", "  ")
}

type openAPIOp struct {
	Summary string `json:"summary"`
	// GraphQL is x-tt-graphql: the request goes to the endpoint with a
	// GraphQL body (event.md 6).
	GraphQL *struct {
		Endpoint string `json:"endpoint"`
		Name     string `json:"name"`
		Document string `json:"document"`
	} `json:"x-tt-graphql"`
	OperationID string `json:"operationId"`
	Parameters  []struct {
		Name     string         `json:"name"`
		In       string         `json:"in"`
		Required bool           `json:"required"`
		Schema   map[string]any `json:"schema"`
	} `json:"parameters"`
	RequestBody *struct {
		Content map[string]openAPIMedia `json:"content"`
	} `json:"requestBody"`
	Responses map[string]struct {
		Description string                  `json:"description"`
		Content     map[string]openAPIMedia `json:"content"`
	} `json:"responses"`
}

type openAPIMedia struct {
	Schema   map[string]any `json:"schema"`
	Examples map[string]struct {
		Value any `json:"value"`
	} `json:"examples"`
}

func isHTTPMethod(m string) bool {
	switch strings.ToUpper(m) {
	case "GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS", "TRACE":
		return true
	}
	return false
}

func methodRank(m string) int {
	for i, k := range []string{"get", "post", "put", "patch", "delete"} {
		if strings.EqualFold(m, k) {
			return i
		}
	}
	return 9
}

func firstSegment(path string) string {
	segs := strings.Split(strings.Trim(path, "/"), "/")
	if len(segs) == 0 || segs[0] == "" {
		return "root"
	}
	return segs[0]
}

// pickExample returns the most useful example of a media type: typical,
// then minimal, then the first by name.
func pickExample(m openAPIMedia) (any, bool) {
	for _, k := range []string{"typical", "minimal"} {
		if e, ok := m.Examples[k]; ok {
			return e.Value, true
		}
	}
	names := make([]string, 0, len(m.Examples))
	for k := range m.Examples {
		names = append(names, k)
	}
	sort.Strings(names)
	if len(names) > 0 {
		return m.Examples[names[0]].Value, true
	}
	return nil, false
}

func pickMedia(content map[string]openAPIMedia) (string, openAPIMedia, bool) {
	if m, ok := content["application/json"]; ok {
		return "application/json", m, true
	}
	names := make([]string, 0, len(content))
	for k := range content {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, k := range names {
		if strings.Contains(k, "json") {
			return k, content[k], true
		}
	}
	if len(names) > 0 {
		return names[0], content[names[0]], true
	}
	return "", openAPIMedia{}, false
}

// sampleValue is the placeholder of a path or query parameter.
func sampleValue(schema map[string]any) string {
	if enum, ok := schema["enum"].([]any); ok && len(enum) > 0 {
		return fmt.Sprint(enum[0])
	}
	switch fmt.Sprint(schema["type"]) {
	case "integer", "number":
		return "1"
	case "boolean":
		return "true"
	}
	switch fmt.Sprint(schema["format"]) {
	case "uuid":
		return "00000000-0000-4000-8000-000000000001"
	case "date":
		return "2026-01-01"
	case "date-time":
		return "2026-01-01T00:00:00Z"
	}
	return "example"
}

func postmanRequest(method, path string, op *openAPIOp) pmItem {
	opPath := path
	if op.GraphQL != nil && op.GraphQL.Endpoint != "" {
		path = op.GraphQL.Endpoint // the logical operation "/graphql#GetOrder" is sent to "/graphql"
	}
	// Path: /orders/{id} -> orders, :id
	var segs []any
	var pathVars []any
	vars := map[string]string{}
	for _, p := range op.Parameters {
		if p.In == "path" {
			vars[p.Name] = sampleValue(p.Schema)
		}
	}
	raw := ""
	for _, s := range strings.Split(strings.Trim(path, "/"), "/") {
		if s == "" {
			continue
		}
		if strings.HasPrefix(s, "{") && strings.HasSuffix(s, "}") {
			n := s[1 : len(s)-1]
			s = ":" + n
			v := vars[n]
			if v == "" {
				v = "example"
			}
			pathVars = append(pathVars, map[string]any{"key": n, "value": v})
		}
		segs = append(segs, s)
		raw += "/" + s
	}
	var query []any
	var headers []any
	rawQuery := ""
	for _, p := range op.Parameters {
		switch p.In {
		case "query":
			v := sampleValue(p.Schema)
			if t, _ := p.Schema["type"].(string); t == "array" {
				if items, ok := p.Schema["items"].(map[string]any); ok {
					v = sampleValue(items)
				}
			}
			query = append(query, map[string]any{"key": p.Name, "value": v, "disabled": !p.Required})
			if p.Required {
				if rawQuery == "" {
					rawQuery = "?"
				} else {
					rawQuery += "&"
				}
				rawQuery += p.Name + "=" + v
			}
		case "header":
			headers = append(headers, map[string]any{"key": p.Name, "value": sampleValue(p.Schema), "disabled": !p.Required})
		}
	}
	url := map[string]any{
		"raw":  "{{" + PostmanBaseURLVar + "}}" + raw + rawQuery,
		"host": []any{"{{" + PostmanBaseURLVar + "}}"},
		"path": segs,
	}
	if len(query) > 0 {
		url["query"] = query
	}
	if len(pathVars) > 0 {
		url["variable"] = pathVars
	}
	req := map[string]any{"method": method, "url": url}

	if op.GraphQL != nil {
		// Postman's GraphQL body: the observed document, its placeholders
		// replaced by neutral literals, and the example variables.
		vars := "{}"
		if op.RequestBody != nil {
			if _, media, ok := pickMedia(op.RequestBody.Content); ok {
				if ex, ok := pickExample(media); ok {
					if m, ok := ex.(map[string]any); ok && m["variables"] != nil {
						b, _ := json.MarshalIndent(m["variables"], "", "  ")
						vars = string(b)
					}
				}
			}
		}
		headers = append(headers, map[string]any{"key": "Content-Type", "value": "application/json"})
		req["body"] = map[string]any{"mode": "graphql", "graphql": map[string]any{"query": graphql.RunnableDocument(op.GraphQL.Document), "variables": vars}}
	} else if op.RequestBody != nil {
		if ct, media, ok := pickMedia(op.RequestBody.Content); ok {
			headers = append(headers, map[string]any{"key": "Content-Type", "value": ct})
			if ex, ok := pickExample(media); ok {
				body, _ := json.MarshalIndent(ex, "", "  ")
				req["body"] = map[string]any{"mode": "raw", "raw": string(body), "options": map[string]any{"raw": map[string]any{"language": "json"}}}
			}
		}
	}
	headers = append(headers, map[string]any{"key": "Accept", "value": "application/json"})
	req["header"] = headers

	name := method + " " + opPath
	if op.GraphQL != nil && op.Summary != "" {
		name = op.Summary // QUERY GetOrder
	}
	item := pmItem{"name": name, "request": req}
	if op.Summary != "" {
		req["description"] = op.Summary
	}

	// Saved responses: one per status code that has an example.
	codes := make([]string, 0, len(op.Responses))
	for c := range op.Responses {
		codes = append(codes, c)
	}
	sort.Strings(codes)
	var saved []any
	for _, c := range codes {
		code, err := strconv.Atoi(c)
		if err != nil {
			continue
		}
		r := op.Responses[c]
		resp := map[string]any{
			"name": c + " " + r.Description, "originalRequest": req, "status": r.Description, "code": code,
			"_postman_previewlanguage": "json",
		}
		if ct, media, ok := pickMedia(r.Content); ok {
			resp["header"] = []any{map[string]any{"key": "Content-Type", "value": ct}}
			if ex, ok := pickExample(media); ok {
				body, _ := json.MarshalIndent(ex, "", "  ")
				resp["body"] = string(body)
			}
		}
		saved = append(saved, resp)
	}
	if len(saved) > 0 {
		item["response"] = saved
	}
	return item
}
